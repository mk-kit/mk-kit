#!/usr/bin/env node
/**
 * Generate projects/docs/src/app/shared/mk-selectors.ts — a map from every
 * public selector token of @mk-kit/ui (`mk-button`, `mkButton`, …) to the class
 * that provides it. The docs use it to work out which classes an example needs
 * when opening it in StackBlitz.
 *
 *   node scripts/gen-selectors.mjs          # write the file
 *   node scripts/gen-selectors.mjs --check  # exit 1 when the file is stale
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const LIB = join(ROOT, 'projects/mk-kit');
const OUT = join(ROOT, 'projects/docs/src/app/shared/mk-selectors.ts');

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === 'schematics') continue;
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (p.endsWith('.ts') && !p.endsWith('.spec.ts')) yield p;
  }
}

const map = new Map();
const decoratorRe = /@(Component|Directive)\(\{([\s\S]*?)\}\)\s*export\s+class\s+(\w+)/g;
const pipeRe = /@Pipe\(\{\s*name:\s*'(\w+)'[\s\S]*?\}\)\s*export\s+class\s+(\w+)/g;
for (const file of walk(LIB)) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(decoratorRe)) {
    const body = m[2];
    const cls = m[3];
    const sel = /selector:\s*'([^']+)'/.exec(body) ?? /selector:\s*"([^"]+)"/.exec(body);
    if (!sel) continue;
    for (const part of sel[1].split(',')) {
      const p = part.trim();
      const tag = /^([a-z][\w-]*)/.exec(p);
      if (tag && tag[1].startsWith('mk-')) map.set(tag[1], cls);
      for (const attr of p.matchAll(/\[(\w+)\]/g)) if (attr[1].startsWith('mk')) map.set(attr[1], cls);
    }
  }
  // Pipes: `{{ x | mkCurrency }}` → MkCurrencyPipe.
  for (const m of src.matchAll(pipeRe)) {
    if (m[1].startsWith('mk')) map.set(m[1], m[2]);
  }
}

const entries = [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const out =
  `// GENERATED by scripts/gen-selectors.mjs — do not edit.\n` +
  `// Selector token (element or attribute) → class exported from @mk-kit/ui.\n` +
  `export const MK_SELECTORS: Readonly<Record<string, string>> = {\n` +
  entries.map(([k, v]) => `  '${k}': '${v}',`).join('\n') +
  `\n};\n`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== out) {
    console.error(`${relative(ROOT, OUT)} is stale — run: node scripts/gen-selectors.mjs`);
    process.exit(1);
  }
  console.log(`${relative(ROOT, OUT)} is up to date (${entries.length} selectors).`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${relative(ROOT, OUT)} (${entries.length} selectors).`);
}
